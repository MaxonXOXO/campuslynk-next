#!/bin/sh
set -e

# -----------------------------------------------------------------------------
# Academic Suite - On-Premise Appliance Secrets Initializer (POSIX Shell)
# -----------------------------------------------------------------------------
# Generates a dedicated .env file before the first 'docker compose up' with:
# - Unique 32-byte AES-256 APP_KEY
# - Unique cryptographically secure passwords for every database role:
#   academic_admin, provisioner, landlord_app, pgbouncer_auth, and Redis.
# - Restrictive file permissions (chmod 600).
# Refuses to overwrite an existing .env unless --force is specified.
# -----------------------------------------------------------------------------

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
TARGET_ENV="${1:-$SCRIPT_DIR/.env}"
FORCE=0

for arg in "$@"; do
    case "$arg" in
        --force|-f)
            FORCE=1
            ;;
    esac
done

if [ -f "$TARGET_ENV" ] && [ "$FORCE" -ne 1 ]; then
    echo "Warning: Secrets file already exists at: $TARGET_ENV"
    echo "To overwrite, rerun with --force: $0 --force"
    exit 0
fi

rand_pass() {
    # Generate 32-char alphanumeric random string
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 16
    else
        head -c 32 /dev/urandom | base64 | tr -dc 'a-zA-Z0-9' | head -c 32
    fi
}

gen_app_key() {
    if command -v openssl >/dev/null 2>&1; then
        echo "base64:$(openssl rand -base64 32)"
    else
        echo "base64:$(head -c 32 /dev/urandom | base64)"
    fi
}

APP_KEY="$(gen_app_key)"
POSTGRES_ADMIN_PASSWORD="$(rand_pass)"
PROVISIONER_PASSWORD="$(rand_pass)"
LANDLORD_APP_PASSWORD="$(rand_pass)"
PGBOUNCER_AUTH_PASSWORD="$(rand_pass)"
REDIS_PASSWORD="$(rand_pass)"

cat <<EOF > "$TARGET_ENV"
# -----------------------------------------------------------------------------
# Academic Suite - On-Premise Appliance Environment Configuration
# Automatically generated by init-secrets.sh on $(date -u +"%Y-%m-%d %H:%M:%SZ")
# -----------------------------------------------------------------------------

# Deployment Profile
DEPLOY_PROFILE=onprem
APP_ENV=production
APP_DEBUG=false

# Application Encryption Key (AES-256-CBC)
APP_KEY=$APP_KEY

# Superuser Role (Internal Postgres init only, never exposed to containers)
POSTGRES_ADMIN_USER=academic_admin
POSTGRES_ADMIN_PASSWORD=$POSTGRES_ADMIN_PASSWORD

# Ops Provisioner Role (Ops service only: DDL, migrations, tenant provisioning)
PROVISIONER_USER=provisioner
PROVISIONER_PASSWORD=$PROVISIONER_PASSWORD

# Runtime App Role (Public API & queue workers: DML only on landlord)
LANDLORD_APP_USER=landlord_app
LANDLORD_APP_PASSWORD=$LANDLORD_APP_PASSWORD

# PgBouncer Auth Role (Lookup function user_search only)
PGBOUNCER_AUTH_USER=pgbouncer_auth
PGBOUNCER_AUTH_PASSWORD=$PGBOUNCER_AUTH_PASSWORD

# Redis Password
REDIS_PASSWORD=$REDIS_PASSWORD

# Legacy / Backward-Compatibility Aliases
DB_PASSWORD=$LANDLORD_APP_PASSWORD
ADMIN_DB_PASSWORD=$PROVISIONER_PASSWORD

# Network Ports
API_PORT=8000
WEB_PORT=3000
POSTGRES_PORT=5432
PGBOUNCER_PORT=6432
REDIS_PORT=6379

# Service URLs
API_URL=http://localhost:8000
WEB_URL=http://localhost:3000
EOF

chmod 600 "$TARGET_ENV"

echo "Generated unique secrets at: $TARGET_ENV"
echo "APP_KEY: $APP_KEY"
echo "Permissions set to 0600 (owner read/write only)."

