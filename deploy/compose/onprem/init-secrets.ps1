<#
.SYNOPSIS
    Generates secure, isolated secrets and initializes .env for Academic Suite On-Premise appliance.

.DESCRIPTION
    Creates a dedicated .env file before the first 'docker compose up' with:
    - Unique 32-byte AES-256 APP_KEY
    - Unique cryptographically secure passwords for every database role:
      academic_admin, provisioner, landlord_app, pgbouncer_auth, and Redis.
    - Restrictive file permissions (only current user and Administrators).
    Refuses to overwrite an existing .env unless -Force is specified.

.PARAMETER EnvFile
    Path to the target .env file. Defaults to .env in this directory.

.PARAMETER Force
    Overwrite existing .env file if it exists.
#>

[CmdletBinding()]
param(
    [string]$EnvFile = "",
    [switch]$Force
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

if (-not $EnvFile) {
    $EnvFile = Join-Path $PSScriptRoot ".env"
}

if (Test-Path -Path $EnvFile) {
    if (-not $Force) {
        Write-Warning "Secrets file already exists at: $EnvFile"
        Write-Host "To regenerate secrets, run with -Force: .\init-secrets.ps1 -Force"
        exit 0
    }
    Write-Host "Overwriting existing secrets file (-Force specified)..."
}

function New-RandomPassword {
    param([int]$Length = 32)
    $chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
    $bytes = New-Object byte[] $Length
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    $result = New-Object char[] $Length
    for ($i = 0; $i -lt $Length; $i++) {
        $result[$i] = $chars[$bytes[$i] % $chars.Length]
    }
    return -join $result
}

function New-AppKey {
    $bytes = New-Object byte[] 32
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    return "base64:" + [Convert]::ToBase64String($bytes)
}

$appKey = New-AppKey
$postgresAdminPassword = New-RandomPassword
$provisionerPassword = New-RandomPassword
$landlordAppPassword = New-RandomPassword
$pgbouncerAuthPassword = New-RandomPassword
$redisPassword = New-RandomPassword

$content = @"
# -----------------------------------------------------------------------------
# Academic Suite - On-Premise Appliance Environment Configuration
# Automatically generated by init-secrets.ps1 on $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
# -----------------------------------------------------------------------------

# Deployment Profile
DEPLOY_PROFILE=onprem
APP_ENV=production
APP_DEBUG=false

# Application Encryption Key (AES-256-CBC)
APP_KEY=$appKey

# Superuser Role (Internal Postgres init only, never exposed to containers)
POSTGRES_ADMIN_USER=academic_admin
POSTGRES_ADMIN_PASSWORD=$postgresAdminPassword

# Ops Provisioner Role (Ops service only: DDL, migrations, tenant provisioning)
PROVISIONER_USER=provisioner
PROVISIONER_PASSWORD=$provisionerPassword

# Runtime App Role (Public API & queue workers: DML only on landlord)
LANDLORD_APP_USER=landlord_app
LANDLORD_APP_PASSWORD=$landlordAppPassword

# PgBouncer Auth Role (Lookup function user_search only)
PGBOUNCER_AUTH_USER=pgbouncer_auth
PGBOUNCER_AUTH_PASSWORD=$pgbouncerAuthPassword

# Redis Password
REDIS_PASSWORD=$redisPassword

# Legacy / Backward-Compatibility Aliases
DB_PASSWORD=$landlordAppPassword
ADMIN_DB_PASSWORD=$provisionerPassword

# Network Ports
API_PORT=8000
WEB_PORT=3000
POSTGRES_PORT=5432
PGBOUNCER_PORT=6432
REDIS_PORT=6379

# Service URLs
API_URL=http://localhost:8000
WEB_URL=http://localhost:3000
"@

# Write UTF8 without BOM
[System.IO.File]::WriteAllText($EnvFile, $content, [System.Text.Encoding]::ASCII)

# Apply restrictive file permissions on Windows
try {
    $acl = Get-Acl -Path $EnvFile
    $acl.SetAccessRuleProtection($true, $false)
    $currentUser = [System.Security.Principal.WindowsIdentity]::GetCurrent().Name
    $rule = New-Object System.Security.Principal.NTAccount($currentUser)
    $accessRule = New-Object System.Security.AccessControl.FileSystemAccessRule(
        $rule,
        "FullControl",
        "Allow"
    )
    $acl.ResetAccessRule($accessRule)
    Set-Acl -Path $EnvFile -AclObject $acl
} catch {
    Write-Warning "Could not restrict Windows ACL on ${EnvFile}: $_"
}

Write-Host "Generated unique secrets at: $EnvFile"
Write-Host "APP_KEY: $appKey"
Write-Host "File permissions restricted to current user."

